pub fn archive_repaired_tutorial_winding_ownership(
    project_root: impl AsRef<Path>,
) -> Result<StaticWorldWindingArchiveReport> {
    let project_root = canonical_directory(project_root.as_ref(), "project root")?;
    let asset_root = canonical_directory(&project_root.join("assets/game"), "asset root")?;
    let active = safe_join(&asset_root, TUTORIAL_STATIC_WORLD_OWNERSHIP_PATH)?;

    if !active.exists() {
        let archived = repaired_tutorial_ownership_path(&project_root, &asset_root)?;
        let revision_root = archived
            .ancestors()
            .nth(5)
            .ok_or_else(|| invalid_error("archived tutorial ownership has no revision root"))?;
        let plan_blake3 = revision_root
            .file_name()
            .and_then(|value| value.to_str())
            .ok_or_else(|| invalid_error("revision root has no UTF-8 plan hash"))?;
        let metadata = revision_metadata(&archived)?;
        validate_winding_revision(revision_root, plan_blake3, &metadata)?;
        return Ok(StaticWorldWindingArchiveReport {
            schema: STATIC_WORLD_WINDING_ARCHIVE_SCHEMA.to_owned(),
            source_build: TUTORIAL_STATIC_WORLD_SOURCE_BUILD.to_owned(),
            revision_plan_blake3: plan_blake3.to_owned(),
            ownership_source: TUTORIAL_STATIC_WORLD_OWNERSHIP_PATH.to_owned(),
            ownership_archive: project_relative(&project_root, &archived)?,
            bytes: metadata.bytes,
            blake3: metadata.blake3,
            already_archived: true,
        });
    }

    let ownership =
        read_json::<TutorialStaticWorldOwnership>(&active, "active repaired tutorial ownership")?;
    if ownership.source_build != TUTORIAL_STATIC_WORLD_SOURCE_BUILD
        || ownership.winding_repair.is_none()
    {
        return invalid("active tutorial ownership has no applied winding-repair proof");
    }
    let active_bytes = read_regular_file(&active, "active repaired tutorial ownership")?;
    let metadata = ArchivedRuntimeMetadata {
        source_path: TUTORIAL_STATIC_WORLD_OWNERSHIP_PATH.to_owned(),
        archive_path: format!("files/{TUTORIAL_STATIC_WORLD_OWNERSHIP_PATH}"),
        reason: "tutorial static-world ownership was regenerated by the audited asset-level winding repair and is retained as offline conversion evidence".to_owned(),
        bytes: active_bytes.len() as u64,
        blake3: hash_bytes(&active_bytes),
        manifested: false,
        manifest_source_path: None,
        manifest_kind: None,
    };
    let files = vec![metadata.clone()];
    let identity = RevisionPlanIdentity {
        schema: REVISION_PLAN_SCHEMA,
        source_build: TUTORIAL_STATIC_WORLD_SOURCE_BUILD,
        files: &files,
    };
    let identity_bytes = serde_json::to_vec(&identity).map_err(generated_json_error)?;
    let plan_blake3 = hash_bytes(&identity_bytes);
    let revisions_root = project_root.join(format!(
        "../FusionForge/work/ffone/migration-archive/{}/conversion-metadata/revisions",
        TUTORIAL_STATIC_WORLD_SOURCE_BUILD
    ));
    let revisions_metadata =
        fs::symlink_metadata(&revisions_root).map_err(|error| io_at(&revisions_root, error))?;
    if revisions_metadata.file_type().is_symlink() || !revisions_metadata.is_dir() {
        return invalid("conversion-metadata revisions root is invalid");
    }
    let revision_root = revisions_root.join(&plan_blake3);
    let archived = revision_root.join(&metadata.archive_path);

    if revision_root.exists() {
        validate_winding_revision(&revision_root, &plan_blake3, &metadata)?;
    } else {
        let stage = revisions_root.join(format!(".winding-repair-stage-{plan_blake3}"));
        if stage.exists() {
            return invalid(format!(
                "stale winding-repair revision stage requires inspection: {}",
                stage.display()
            ));
        }
        fs::create_dir(&stage).map_err(|error| io_at(&stage, error))?;
        let staged_archive = stage.join(&metadata.archive_path);
        write_new(&staged_archive, &active_bytes)?;
        let index = RevisionIndex {
            schema: REVISION_INDEX_SCHEMA.to_owned(),
            source_build: TUTORIAL_STATIC_WORLD_SOURCE_BUILD.to_owned(),
            plan_blake3: plan_blake3.clone(),
            files: files.clone(),
        };
        let report = RevisionReport {
            schema: REVISION_REPORT_SCHEMA.to_owned(),
            source_build: TUTORIAL_STATIC_WORLD_SOURCE_BUILD.to_owned(),
            plan_blake3: plan_blake3.clone(),
            archived_files: 1,
            archived_bytes: metadata.bytes,
            files,
        };
        write_new(&stage.join("index.json"), &pretty_json(&index)?)?;
        write_new(&stage.join("report.json"), &pretty_json(&report)?)?;
        validate_winding_revision(&stage, &plan_blake3, &metadata)?;
        fs::rename(&stage, &revision_root).map_err(|error| io_at(&revision_root, error))?;
    }

    let current = read_regular_file(&active, "active repaired tutorial ownership")?;
    if current != active_bytes {
        return invalid("active tutorial ownership changed while it was being archived");
    }
    fs::remove_file(&active).map_err(|error| io_at(&active, error))?;

    Ok(StaticWorldWindingArchiveReport {
        schema: STATIC_WORLD_WINDING_ARCHIVE_SCHEMA.to_owned(),
        source_build: TUTORIAL_STATIC_WORLD_SOURCE_BUILD.to_owned(),
        revision_plan_blake3: plan_blake3,
        ownership_source: TUTORIAL_STATIC_WORLD_OWNERSHIP_PATH.to_owned(),
        ownership_archive: project_relative(&project_root, &archived)?,
        bytes: metadata.bytes,
        blake3: metadata.blake3,
        already_archived: false,
    })
}

pub(super) fn revision_metadata(path: &Path) -> Result<ArchivedRuntimeMetadata> {
    let bytes = read_regular_file(path, "archived repaired tutorial ownership")?;
    Ok(ArchivedRuntimeMetadata {
        source_path: TUTORIAL_STATIC_WORLD_OWNERSHIP_PATH.to_owned(),
        archive_path: format!("files/{TUTORIAL_STATIC_WORLD_OWNERSHIP_PATH}"),
        reason: "tutorial static-world ownership was regenerated by the audited asset-level winding repair and is retained as offline conversion evidence".to_owned(),
        bytes: bytes.len() as u64,
        blake3: hash_bytes(&bytes),
        manifested: false,
        manifest_source_path: None,
        manifest_kind: None,
    })
}

pub fn verify_static_world_winding(
    project_root: impl AsRef<Path>,
    report_path: impl AsRef<Path>,
) -> Result<StaticWorldWindingVerification> {
    let project_root = canonical_directory(project_root.as_ref(), "project root")?;
    let asset_root = canonical_directory(&project_root.join("assets/game"), "asset root")?;
    let report_path =
        absolute_under_project(&project_root, report_path.as_ref(), "winding repair report")?;
    let report = read_json::<StaticWorldWindingRepairReport>(
        &report_path,
        "static-world winding repair report",
    )?;
    if report.schema != STATIC_WORLD_WINDING_REPAIR_SCHEMA
        || report.mode != StaticWorldWindingRepairMode::Apply
        || report.source_build != TUTORIAL_STATIC_WORLD_SOURCE_BUILD
    {
        return invalid("verification requires an applied v1 winding repair report");
    }

    let mut actual_hashes = BTreeMap::<String, (u64, String)>::new();
    let mut scope_hashers = report
        .scopes
        .iter()
        .map(|scope| (scope.scope.clone(), blake3::Hasher::new()))
        .collect::<BTreeMap<_, _>>();
    let mut triangles = 0_u64;
    let mut normal_bearing_files = 0_u64;
    let mut normal_less_files = 0_u64;
    for (index, expected) in report.files.iter().enumerate() {
        let path = safe_join(&asset_root, &expected.path)?;
        let bytes = read_regular_file(&path, "repaired static-world GLB")?;
        let hash = hash_bytes(&bytes);
        if bytes.len() as u64 != expected.bytes || hash != expected.result_blake3 {
            return invalid(format!(
                "repaired file differs from apply report at {:?}",
                expected.path
            ));
        }
        let stats = analyze_glb(&bytes, &expected.path)?;
        if stats.normal_bearing && stats.aligned <= stats.opposed {
            return invalid(format!(
                "repaired file remains predominantly opposed at {:?}: {stats:?}",
                expected.path
            ));
        }
        if stats.normal_bearing != expected.normal_bearing
            || stats.index_accessors != expected.index_accessors
            || stats.triangles != expected.triangles
            || stats.aligned != expected.aligned_after
            || stats.opposed != expected.opposed_after
            || stats.degenerate != expected.degenerate
            || stats.tangent_accessors != expected.tangent_accessors
        {
            return invalid(format!(
                "repaired geometry evidence differs from apply report at {:?}",
                expected.path
            ));
        }
        let hasher = scope_hashers.get_mut(&expected.scope).ok_or_else(|| {
            invalid_error(format!(
                "report file has unknown scope {:?}",
                expected.scope
            ))
        })?;
        append_set_hash(hasher, &expected.path, &hash);
        if actual_hashes
            .insert(expected.path.clone(), (bytes.len() as u64, hash))
            .is_some()
        {
            return invalid(format!("duplicate report path {:?}", expected.path));
        }
        triangles += stats.triangles;
        normal_bearing_files += u64::from(stats.normal_bearing);
        normal_less_files += u64::from(!stats.normal_bearing);
        if (index + 1) % 25_000 == 0 || index + 1 == report.files.len() {
            eprintln!(
                "verification: hashed {}/{} repaired visual GLBs",
                index + 1,
                report.files.len()
            );
        }
    }

    let mut aggregate = blake3::Hasher::new();
    for scope in &report.scopes {
        let actual = scope_hashers
            .remove(&scope.scope)
            .expect("scope hasher created from same report")
            .finalize()
            .to_hex()
            .to_string();
        if actual != scope.result_set_blake3 {
            return invalid(format!(
                "{} repaired result set hash differs from its report",
                scope.scope
            ));
        }
        append_set_hash(&mut aggregate, &scope.scope, &actual);
    }
    let aggregate = aggregate.finalize().to_hex().to_string();
    if aggregate != report.result_set_blake3 {
        return invalid("aggregate repaired result set hash differs from its report");
    }

    let world_ownership_path = safe_join(&asset_root, WORLD_MAP_STATIC_WORLD_OWNERSHIP_PATH)?;
    let tutorial_ownership_path = repaired_tutorial_ownership_path(&project_root, &asset_root)?;
    let ownership_paths = [
        ("worldMap", world_ownership_path),
        ("tutorial", tutorial_ownership_path),
    ];
    let mut scene_count = 0_u64;
    let mut seen_models = BTreeSet::new();
    for (scope_label, ownership_path) in ownership_paths {
        let ownership = read_json::<TutorialStaticWorldOwnership>(
            &ownership_path,
            "repaired static-world ownership",
        )?;
        let scope_report = report
            .scopes
            .iter()
            .find(|scope| scope.scope == scope_label)
            .ok_or_else(|| invalid_error(format!("report lacks {scope_label} scope")))?;
        let proof = ownership.winding_repair.as_ref().ok_or_else(|| {
            invalid_error(format!(
                "{scope_label} ownership lacks winding repair proof"
            ))
        })?;
        if proof.schema != STATIC_WORLD_WINDING_REPAIR_PROOF_SCHEMA
            || proof.result_set_blake3 != scope_report.result_set_blake3
            || proof.source_set_blake3 != scope_report.source_set_blake3
            || proof.visual_files != scope_report.visual_files
            || proof.converted_files != scope_report.converted_files
            || proof.unchanged_files != scope_report.unchanged_files
        {
            return invalid(format!(
                "{scope_label} ownership winding proof differs from apply report"
            ));
        }
        for entry in &ownership.owned_files {
            let Some((bytes, hash)) = actual_hashes.get(&entry.path) else {
                continue;
            };
            if entry.bytes != *bytes || entry.blake3 != *hash {
                return invalid(format!(
                    "{scope_label} ownership file proof differs at {:?}",
                    entry.path
                ));
            }
        }
        for scene in &ownership.scenes {
            let path = safe_join(&asset_root, &scene.path)?;
            let bytes = read_regular_file(&path, "repaired static-world scene")?;
            if bytes.len() as u64 != scene.installed_bytes
                || hash_bytes(&bytes) != scene.installed_blake3
            {
                return invalid(format!("scene proof differs at {:?}", scene.path));
            }
            let value: JsonValue = parse_json(&bytes, &path)?;
            if static_fields_blake3(&value)? != scene.static_fields_blake3 {
                return invalid(format!("scene static proof differs at {:?}", scene.path));
            }
            for model in required_array(&value, "models", &scene.path)? {
                let Some(model_path) = model.get("path").and_then(JsonValue::as_str) else {
                    return invalid(format!("scene {:?} model has no path", scene.path));
                };
                let Some((_, expected_hash)) = actual_hashes.get(model_path) else {
                    continue;
                };
                if model.get("blake3").and_then(JsonValue::as_str) != Some(expected_hash.as_str())
                    || !seen_models.insert(model_path.to_owned())
                {
                    return invalid(format!(
                        "scene {:?} has invalid/duplicate repaired model {model_path:?}",
                        scene.path
                    ));
                }
            }
            scene_count += 1;
        }
    }
    if seen_models.len() != actual_hashes.len() {
        return invalid(format!(
            "scene closure covers {}/{} repaired models",
            seen_models.len(),
            actual_hashes.len()
        ));
    }

    let runtime_path = safe_join(&asset_root, RUNTIME_WORLD_PATH)?;
    let runtime = read_regular_file(&runtime_path, "runtime world registry")?;
    let runtime_hash = hash_bytes(&runtime);
    if runtime_hash != report.runtime_world_after_blake3 {
        return invalid("runtime world registry differs from apply report");
    }

    Ok(StaticWorldWindingVerification {
        schema: "ffone.static-world-winding-verification.v1".to_owned(),
        source_report: project_relative(&project_root, &report_path)?,
        visual_files: actual_hashes.len() as u64,
        scene_files: scene_count,
        triangles,
        normal_bearing_files,
        normal_less_files,
        result_set_blake3: aggregate,
        runtime_world_blake3: runtime_hash,
    })
}

pub fn repair_static_world_winding(
    options: &StaticWorldWindingRepairOptions,
) -> Result<StaticWorldWindingRepairReport> {
    let project_root = canonical_directory(&options.project_root, "project root")?;
    let asset_root = canonical_directory(&project_root.join("assets/game"), "asset root")?;
    let report_path = absolute_under_project(&project_root, &options.report_path, "report path")?;
    if report_path.starts_with(&asset_root) {
        return invalid("repair report must remain outside the runtime asset tree");
    }
    let report_relative = project_relative(&project_root, &report_path)?;
    let backup_root =
        project_root.join("target/ffone-migration/world-static-winding-repair/backup-v1");
    if !backup_root.starts_with(&project_root) || backup_root.starts_with(&asset_root) {
        return invalid("repair backup root escaped its generated project directory");
    }
    if options.apply {
        initialize_backup_root(&backup_root, &project_root)?;
    }

    let mut scopes = vec![
        load_world_map_scope(&asset_root)?,
        load_tutorial_scope(&project_root, &asset_root)?,
    ];
    let mode = if options.apply {
        StaticWorldWindingRepairMode::Apply
    } else {
        StaticWorldWindingRepairMode::Plan
    };
    let mut files = Vec::new();
    let mut counts = StaticWorldWindingRepairCounts::default();
    let mut result_hashes = BTreeMap::<String, (u64, String)>::new();

    for scope in &mut scopes {
        if scope.ownership.source_build != TUTORIAL_STATIC_WORLD_SOURCE_BUILD {
            return invalid(format!(
                "{} ownership has unexpected source build {:?}",
                scope.label, scope.ownership.source_build
            ));
        }
        if scope.ownership.winding_repair.is_some() {
            return invalid(format!(
                "{} ownership already contains a winding repair proof",
                scope.label
            ));
        }

        let mut selected = scope
            .ownership
            .owned_files
            .iter()
            .filter(|entry| is_visual_glb(&entry.path, scope.label))
            .map(|entry| (entry.path.clone(), entry.bytes, entry.blake3.clone()))
            .collect::<Vec<_>>();
        selected.sort_by(|left, right| left.0.cmp(&right.0));
        if selected.is_empty() {
            return invalid(format!("{} ownership contains no visual GLBs", scope.label));
        }
        if selected.windows(2).any(|pair| pair[0].0 == pair[1].0) {
            return invalid(format!(
                "{} ownership contains duplicate visual GLB paths",
                scope.label
            ));
        }

        scope.file_start = files.len();
        let mut source_set = blake3::Hasher::new();
        let mut result_set = blake3::Hasher::new();
        for (index, (relative, expected_bytes, expected_hash)) in selected.iter().enumerate() {
            let path = safe_join(&asset_root, relative)?;
            let original = read_regular_file(&path, "published static-world GLB")?;
            if original.len() as u64 != *expected_bytes {
                return invalid(format!(
                    "{relative:?} bytes differ from ownership: {}/{}",
                    original.len(),
                    expected_bytes
                ));
            }
            let actual_hash = hash_bytes(&original);
            let (source_stats, mut result, result_stats, action) = if actual_hash == *expected_hash
            {
                let before = analyze_glb(&original, relative)?;
                if before.needs_reversal() {
                    let mut repaired = original.clone();
                    reverse_glb_indices(&mut repaired, relative)?;
                    let after = analyze_glb(&repaired, relative)?;
                    require_repair_improves(relative, before, after)?;
                    (
                        before,
                        repaired,
                        after,
                        StaticWorldWindingRepairAction::Converted,
                    )
                } else {
                    (
                        before,
                        original.clone(),
                        before,
                        StaticWorldWindingRepairAction::AlreadyAligned,
                    )
                }
            } else {
                // Resume is accepted only when reversing the current file
                // reproduces the exact ownership hash byte-for-byte.
                let current = analyze_glb(&original, relative)?;
                let mut reversed = original.clone();
                reverse_glb_indices(&mut reversed, relative)?;
                if hash_bytes(&reversed) != *expected_hash {
                    return invalid(format!(
                        "{relative:?} matches neither its ownership hash nor the exact repaired form"
                    ));
                }
                let source = analyze_glb(&reversed, relative)?;
                require_repair_improves(relative, source, current)?;
                (
                    source,
                    original.clone(),
                    current,
                    StaticWorldWindingRepairAction::ResumedConverted,
                )
            };

            let result_hash = hash_bytes(&result);
            if options.apply && action == StaticWorldWindingRepairAction::Converted {
                backup_and_replace(&project_root, &backup_root, &path, &original, &result)?;
                result.clear();
            }
            append_set_hash(&mut source_set, relative, expected_hash);
            append_set_hash(&mut result_set, relative, &result_hash);
            if result_hashes
                .insert(relative.clone(), (*expected_bytes, result_hash.clone()))
                .is_some()
            {
                return invalid(format!("duplicate repaired path {relative:?}"));
            }

            let converted = action != StaticWorldWindingRepairAction::AlreadyAligned;
            scope.converted_files += u64::from(converted);
            scope.unchanged_files += u64::from(!converted);
            counts.visual_files += 1;
            counts.converted_files += u64::from(converted);
            counts.unchanged_files += u64::from(!converted);
            counts.resumed_files +=
                u64::from(action == StaticWorldWindingRepairAction::ResumedConverted);
            counts.normal_bearing_files += u64::from(source_stats.normal_bearing);
            counts.normal_less_files += u64::from(!source_stats.normal_bearing);
            counts.index_accessors += source_stats.index_accessors;
            counts.triangles += source_stats.triangles;
            counts.aligned_triangles_before += source_stats.aligned;
            counts.opposed_triangles_before += source_stats.opposed;
            counts.aligned_triangles_after += result_stats.aligned;
            counts.opposed_triangles_after += result_stats.opposed;
            counts.degenerate_triangles += source_stats.degenerate;
            counts.tangent_accessors += source_stats.tangent_accessors;
            files.push(StaticWorldWindingRepairFile {
                scope: scope.label.to_owned(),
                path: relative.clone(),
                bytes: *expected_bytes,
                source_blake3: expected_hash.clone(),
                result_blake3: result_hash,
                action,
                normal_bearing: source_stats.normal_bearing,
                index_accessors: source_stats.index_accessors,
                triangles: source_stats.triangles,
                aligned_before: source_stats.aligned,
                opposed_before: source_stats.opposed,
                aligned_after: result_stats.aligned,
                opposed_after: result_stats.opposed,
                degenerate: source_stats.degenerate,
                tangent_accessors: source_stats.tangent_accessors,
            });
            if (index + 1) % 5_000 == 0 || index + 1 == selected.len() {
                eprintln!(
                    "{}: audited {}/{} visual GLBs",
                    scope.label,
                    index + 1,
                    selected.len()
                );
            }
        }
        scope.file_end = files.len();
        scope.source_set_blake3 = source_set.finalize().to_hex().to_string();
        scope.result_set_blake3 = result_set.finalize().to_hex().to_string();
    }

    if counts.tangent_accessors != 0 {
        return invalid(format!(
            "static-world repair found {} unexpected tangent accessors",
            counts.tangent_accessors
        ));
    }

    let mut all_scene_hashes = BTreeMap::<String, String>::new();
    for scope in &mut scopes {
        rewrite_scope_scenes(
            &project_root,
            &asset_root,
            &backup_root,
            options.apply,
            scope,
            &result_hashes,
        )?;
        counts.scene_files += scope.scene_hashes.len() as u64;
        for (path, hash) in &scope.scene_hashes {
            if all_scene_hashes
                .insert(path.clone(), hash.clone())
                .is_some()
            {
                return invalid(format!("duplicate scene proof path {path:?}"));
            }
        }
    }

    let runtime_path = safe_join(&asset_root, RUNTIME_WORLD_PATH)?;
    let runtime_before = read_regular_file(&runtime_path, "runtime world registry")?;
    let runtime_before_hash = hash_bytes(&runtime_before);
    let runtime_after = rewrite_runtime_world(&runtime_before, &runtime_path, &all_scene_hashes)?;
    let runtime_after_hash = hash_bytes(&runtime_after);
    if options.apply && runtime_before != runtime_after {
        backup_and_replace(
            &project_root,
            &backup_root,
            &runtime_path,
            &runtime_before,
            &runtime_after,
        )?;
    }

    for scope in &mut scopes {
        let reference = scope
            .ownership
            .references
            .iter_mut()
            .find(|reference| reference.path == RUNTIME_WORLD_PATH)
            .ok_or_else(|| {
                invalid_error(format!(
                    "{} ownership has no runtime world reference",
                    scope.label
                ))
            })?;
        reference.bytes = runtime_after.len() as u64;
        reference.blake3 = runtime_after_hash.clone();
        reference.scene_count = scope.scene_hashes.len() as u64;

        for entry in &mut scope.ownership.owned_files {
            if let Some((bytes, hash)) = result_hashes.get(&entry.path) {
                entry.bytes = *bytes;
                entry.blake3 = hash.clone();
            }
        }
        scope.ownership.winding_repair = Some(StaticWorldWindingRepairProof {
            schema: STATIC_WORLD_WINDING_REPAIR_PROOF_SCHEMA.to_owned(),
            tool: STATIC_WORLD_WINDING_REPAIR_TOOL.to_owned(),
            operation: OPERATION.to_owned(),
            source_contract: SOURCE_CONTRACT.to_owned(),
            report_path: report_relative.clone(),
            visual_files: (scope.file_end - scope.file_start) as u64,
            converted_files: scope.converted_files,
            unchanged_files: scope.unchanged_files,
            source_set_blake3: scope.source_set_blake3.clone(),
            result_set_blake3: scope.result_set_blake3.clone(),
        });
        let ownership_bytes = pretty_json(&scope.ownership)?;
        if options.apply {
            if scope.ownership_target.exists() {
                let current = read_regular_file(&scope.ownership_target, "ownership target")?;
                backup_and_replace(
                    &project_root,
                    &backup_root,
                    &scope.ownership_target,
                    &current,
                    &ownership_bytes,
                )?;
            } else {
                write_new(&scope.ownership_target, &ownership_bytes)?;
            }
        }
    }

    let mut aggregate_source = blake3::Hasher::new();
    let mut aggregate_result = blake3::Hasher::new();
    let scope_reports = scopes
        .iter()
        .map(|scope| {
            append_set_hash(&mut aggregate_source, scope.label, &scope.source_set_blake3);
            append_set_hash(&mut aggregate_result, scope.label, &scope.result_set_blake3);
            StaticWorldWindingRepairScopeReport {
                scope: scope.label.to_owned(),
                ownership_source: project_relative(&project_root, &scope.ownership_source)
                    .unwrap_or_else(|_| scope.ownership_source.display().to_string()),
                ownership_target: project_relative(&project_root, &scope.ownership_target)
                    .unwrap_or_else(|_| scope.ownership_target.display().to_string()),
                visual_files: (scope.file_end - scope.file_start) as u64,
                converted_files: scope.converted_files,
                unchanged_files: scope.unchanged_files,
                scene_files: scope.scene_hashes.len() as u64,
                source_set_blake3: scope.source_set_blake3.clone(),
                result_set_blake3: scope.result_set_blake3.clone(),
            }
        })
        .collect::<Vec<_>>();
    let report = StaticWorldWindingRepairReport {
        schema: STATIC_WORLD_WINDING_REPAIR_SCHEMA.to_owned(),
        tool: STATIC_WORLD_WINDING_REPAIR_TOOL.to_owned(),
        source_build: TUTORIAL_STATIC_WORLD_SOURCE_BUILD.to_owned(),
        mode,
        operation: OPERATION.to_owned(),
        source_contract: SOURCE_CONTRACT.to_owned(),
        project_root: path_text(&project_root),
        asset_root: path_text(&asset_root),
        report_path: report_relative,
        backup_root: options
            .apply
            .then(|| project_relative(&project_root, &backup_root))
            .transpose()?,
        scopes: scope_reports,
        counts,
        source_set_blake3: aggregate_source.finalize().to_hex().to_string(),
        result_set_blake3: aggregate_result.finalize().to_hex().to_string(),
        runtime_world_before_blake3: runtime_before_hash,
        runtime_world_after_blake3: runtime_after_hash,
        files,
    };
    write_json_replace(&report_path, &report)?;
    Ok(report)
}

pub(super) fn rewrite_scope_scenes(
    project_root: &Path,
    asset_root: &Path,
    backup_root: &Path,
    apply: bool,
    scope: &mut ScopeWork,
    result_hashes: &BTreeMap<String, (u64, String)>,
) -> Result<()> {
    let scope_paths =
        scope.ownership.owned_files.iter().filter_map(|entry| {
            is_visual_glb(&entry.path, scope.label).then_some(entry.path.clone())
        });
    let mut expected = scope_paths.collect::<BTreeSet<_>>();
    for scene in &mut scope.ownership.scenes {
        let path = safe_join(asset_root, &scene.path)?;
        let before = read_regular_file(&path, "static-world scene")?;
        let mut value: JsonValue = parse_json(&before, &path)?;
        let models = value
            .get_mut("models")
            .and_then(JsonValue::as_array_mut)
            .ok_or_else(|| invalid_error(format!("scene {:?} has no models array", scene.path)))?;
        for model in models {
            let model_path = model
                .get("path")
                .and_then(JsonValue::as_str)
                .ok_or_else(|| invalid_error(format!("scene {:?} model has no path", scene.path)))?
                .to_owned();
            let Some((_, hash)) = result_hashes.get(&model_path) else {
                continue;
            };
            if !expected.remove(&model_path) {
                return invalid(format!(
                    "scene {:?} duplicates or cross-links repaired model {model_path:?}",
                    scene.path
                ));
            }
            model
                .as_object_mut()
                .ok_or_else(|| invalid_error("scene model is not an object"))?
                .insert("blake3".to_owned(), JsonValue::String(hash.clone()));
        }
        let after = pretty_json(&value)?;
        let after_hash = hash_bytes(&after);
        let static_hash = static_fields_blake3(&value)?;
        if apply && before != after {
            backup_and_replace(project_root, backup_root, &path, &before, &after)?;
        }
        scene.static_fields_blake3 = static_hash;
        scene.installed_bytes = after.len() as u64;
        scene.installed_blake3 = after_hash.clone();
        if scope
            .scene_hashes
            .insert(scene.path.clone(), after_hash)
            .is_some()
        {
            return invalid(format!("duplicate scene path {:?}", scene.path));
        }
    }
    if !expected.is_empty() {
        return invalid(format!(
            "{} scenes do not own {} repaired visual GLBs; first={:?}",
            scope.label,
            expected.len(),
            expected.first()
        ));
    }
    Ok(())
}
